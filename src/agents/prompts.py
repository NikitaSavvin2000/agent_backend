agent_intent_prompt = """
    Определи намерение пользователя на основе его запроса.
    Ответь строго одним инструментом в формате Python-списка, например: ["forecast"].
    
    Возможные инструменты:
    1. forecast — если пользователь явно хочет сделать прогноз временного ряда, предсказание будущих значений или моделирование тренда.
    2. visualization — если пользователь хочет построить график, визуализацию данных, или запрос подразумевает, что визуализация необходима.
    3. analysis — если пользователь хочет провести анализ данных, вычислить статистику, найти зависимости или отклонения.
    4. none — если запрос не относится к анализу данных, визуализации или прогнозированию.

    Выбор всегда строго один. 
    Приоритет выбора: forecast > visualization > analysis > none.

    Примеры:
    - "Сделай прогноз продаж на месяц" → ["forecast"]
    - "Построй график распределения и сделай анализ" → ["visualization"]
    - "Проанализируй данные по продажам" → ["analysis"]
    - "Расскажи анекдот" → ["none"]
"""



def build_agent_intent_prompt(message: str, message_context: Optional[str], user_means_context: bool) -> str:
    context_str = ""
    if user_means_context and message_context:
        context_str = f"Пользователь ранее запрашивал: '{message_context}'.\n"

    return f"""
        Ты — помощник для выбора инструмента работы с данными. 
        На вход ты получаешь:
        1. Текущий запрос пользователя: '{message}'.
        2. {context_str if context_str else "Контекст предыдущих запросов отсутствует."}
        
        Выбирай один инструмент строго из: forecast, visualization, analysis, none.
        
        Правила выбора:
        
        1. Если есть контекст (пользователь ранее запрашивал что-то):
            - Считай, что предыдущие запросы уже выполнены.
            - Выбирай инструмент исходя из того, что требуется сейчас по отношению к уже выполненным действиям.
              Например, если ранее строился прогноз, а текущий запрос — работа с этим прогнозом, выбирай analysis, даже если в текущем запросе есть слово "прогноз".
        
        2. Если контекста нет:
            - Выбирай инструмент исходя только из текущего запроса:
                - forecast — прогноз временного ряда, предсказание будущих значений, моделирование тренда.
                - visualization — построение графиков или визуализаций.
                - analysis — анализ данных, вычисление статистики, поиск аномалий, работа с данными.
                - none — если запрос не относится к анализу, визуализации или прогнозированию.
        
        Всегда возвращай только один инструмент в формате Python-списка, например ["forecast"].
     """


